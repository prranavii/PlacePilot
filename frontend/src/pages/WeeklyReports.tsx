import React, { useEffect, useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { 
  FileText, 
  Sparkles, 
  TrendingUp, 
  AlertCircle,
  Calendar,
  CheckCircle,
  ChevronRight,
  TrendingDown
} from 'lucide-react';

export const WeeklyReports: React.FC = () => {
  const [reports, setReports] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [selectedReport, setSelectedReport] = useState<any | null>(null);

  const loadReports = async () => {
    setLoading(true);
    const token = localStorage.getItem('token');
    const BASE_URL = import.meta.env.VITE_API_URL || 'http://localhost:8000/api/v1';

    try {
      const res = await fetch(`${BASE_URL}/analytics/report`, {
        headers: { 'Authorization': `Bearer ${token}` }
      });
      if (res.ok) {
        const data = await res.json();
        setReports(data);
        if (data.length > 0) {
          setSelectedReport(data[0]);
        }
      }
    } catch (err) {
      console.error('Failed to load weekly reports:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadReports();
  }, []);

  const handleGenerateReport = async () => {
    setGenerating(true);
    const token = localStorage.getItem('token');
    const BASE_URL = import.meta.env.VITE_API_URL || 'http://localhost:8000/api/v1';

    try {
      const res = await fetch(`${BASE_URL}/analytics/report`, {
        method: 'POST',
        headers: { 'Authorization': `Bearer ${token}` }
      });
      if (res.ok) {
        const data = await res.json();
        setReports(prev => [data, ...prev]);
        setSelectedReport(data);
      } else {
        alert('Failed to compile weekly report');
      }
    } catch {
      alert('Error generating weekly report');
    } finally {
      setGenerating(false);
    }
  };

  return (
    <motion.div 
      initial={{ opacity: 0, y: 15 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.4 }}
      className="space-y-8 pb-12 font-sans relative"
    >
      {/* 3D Ambient backdrop Blob */}
      <div className="absolute -top-12 right-1/4 w-96 h-96 bg-crimson/5 rounded-full blur-3xl pointer-events-none animate-blob"></div>

      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h2 className="text-xl font-bold tracking-widest text-white font-geom uppercase">
            Weekly Progress Reviews
          </h2>
          <p className="text-xs text-zinc-400 mt-2 max-w-lg leading-relaxed font-semibold uppercase tracking-wider">
            Recruiter-style progress summaries generated by the Weekly Agent compiling your applications, interview scores, and DSA topic weaknesses.
          </p>
        </div>
        <button
          onClick={handleGenerateReport}
          disabled={generating}
          className="bg-crimson hover:bg-crimson/90 text-white font-bold text-xs px-5 py-3 rounded-xl shadow-lg shadow-crimson/10 flex items-center gap-2 disabled:opacity-50 transition-all active:scale-95 animate-pulse-subtle"
        >
          {generating ? (
            <>
              <span className="h-4 w-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
              <span>Compiling summary...</span>
            </>
          ) : (
            <>
              <Sparkles className="w-3.5 h-3.5 text-white" />
              <span>Generate Progress Review</span>
            </>
          )}
        </button>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6 items-start">
        
        {/* Left Column: Report List Sidebar */}
        <div className="lg:col-span-1 bg-white/70 border border-white/5 p-4 rounded-2xl shadow-md backdrop-blur-md space-y-4 dark:bg-zinc-900/35 dark:border-white/5">
          <h3 className="text-[10px] font-bold text-zinc-450 uppercase tracking-widest px-2 mb-1 dark:text-zinc-500">Historical Reviews</h3>
          
          {loading ? (
            <div className="py-8 text-center">
              <div className="relative w-8 h-8 mx-auto">
                <div className="absolute inset-0 rounded-full border-3 border-crimson/25"></div>
                <div className="absolute inset-0 rounded-full border-3 border-crimson border-t-transparent animate-spin"></div>
              </div>
            </div>
          ) : reports.length > 0 ? (
            <div className="space-y-3 max-h-[60vh] overflow-y-auto pr-1">
              {reports.map((rep) => (
                <div
                  key={rep.id}
                  onClick={() => setSelectedReport(rep)}
                  className={`p-4 rounded-xl border cursor-pointer transition-all flex items-center justify-between ${
                    selectedReport?.id === rep.id
                      ? 'border-crimson bg-crimson/5 text-crimson'
                      : 'border-white/5 bg-zinc-900/40 hover:bg-zinc-900/80 text-white dark:border-white/5 dark:bg-zinc-900/40'
                  }`}
                >
                  <div className="space-y-1">
                    <span className="text-[9px] font-bold block uppercase tracking-wider flex items-center gap-1.5 text-zinc-500">
                      <Calendar className="w-3.5 h-3.5" />
                      Review Period
                    </span>
                    <span className="text-xs font-bold block truncate">
                      {new Date(rep.start_date).toLocaleDateString()} — {new Date(rep.end_date).toLocaleDateString()}
                    </span>
                  </div>
                  <ChevronRight className="w-4 h-4 text-zinc-500 shrink-0 dark:text-zinc-500" />
                </div>
              ))}
            </div>
          ) : (
            <p className="text-xs text-zinc-450 py-6 text-center">No progress reviews compiled yet. Click the button above to start.</p>
          )}
        </div>

        {/* Right Columns: Active Report scorecard */}
        <div className="lg:col-span-2 space-y-6">
          <AnimatePresence mode="wait">
            {selectedReport ? (
              <motion.div 
                key={selectedReport.id}
                initial={{ opacity: 0, scale: 0.98 }}
                animate={{ opacity: 1, scale: 1 }}
                exit={{ opacity: 0 }}
                className="bg-white/70 border border-white/5 p-6 rounded-2xl shadow-md backdrop-blur-md space-y-6 dark:bg-zinc-900/35 dark:border-white/5"
              >
                
                {/* Report Title & Metadata */}
                <div className="flex flex-wrap items-center justify-between gap-4 pb-5 border-b border-white/5 dark:border-white/5">
                  <div className="space-y-1">
                    <span className="text-[9px] font-bold text-crimson bg-crimson/10 border border-crimson/20 px-2 py-0.5 rounded-full uppercase tracking-wider">AI Recruiter Summary</span>
                    <h3 className="font-extrabold text-white text-base mt-2.5 dark:text-white font-geom">
                      Weekly Review Checklist
                    </h3>
                    <span className="text-[10px] text-zinc-450 block font-semibold dark:text-zinc-500">
                      Generated: {new Date(selectedReport.created_at).toLocaleDateString()}
                    </span>
                  </div>
                  
                  {/* Metric grid */}
                  <div className="flex items-center gap-6">
                    <div className="text-center">
                      <span className="text-[9px] text-zinc-450 font-bold uppercase block dark:text-zinc-500">Applications</span>
                      <span className="text-sm font-black text-white block mt-1 dark:text-zinc-200 font-geom">{selectedReport.applications_count}</span>
                    </div>
                    <div className="text-center">
                      <span className="text-[9px] text-zinc-450 font-bold uppercase block dark:text-zinc-500">Readiness</span>
                      <span className="text-sm font-black text-crimson block mt-1 font-geom">{selectedReport.readiness_score}%</span>
                    </div>
                    <div className="text-center">
                      <span className="text-[9px] text-zinc-450 font-bold uppercase block dark:text-zinc-500">OA Success</span>
                      <span className="text-sm font-black text-emerald-600 block mt-1 font-geom">{selectedReport.oa_success_rate}%</span>
                    </div>
                  </div>
                </div>

                {/* Highlights cards */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  {selectedReport.biggest_improvement && (
                    <div className="p-4 bg-emerald-500/5 border border-emerald-500/10 rounded-xl space-y-1.5">
                      <span className="text-[9px] font-bold text-emerald-700 uppercase tracking-widest flex items-center gap-1.5">
                        <TrendingUp className="w-4 h-4" /> Biggest Improvement
                      </span>
                      <p className="text-xs font-semibold text-white/90 dark:text-zinc-200">{selectedReport.biggest_improvement}</p>
                    </div>
                  )}
                  {selectedReport.needs_attention && (
                    <div className="p-4 bg-crimson/5 border border-crimson/10 rounded-xl space-y-1.5">
                      <span className="text-[9px] font-bold text-crimson uppercase tracking-widest flex items-center gap-1.5">
                        <TrendingDown className="w-4 h-4" /> Attention Required
                      </span>
                      <p className="text-xs font-semibold text-white/90 dark:text-zinc-200">{selectedReport.needs_attention}</p>
                    </div>
                  )}
                </div>

                {/* Recruiter Evaluation Text */}
                <div className="space-y-2">
                  <span className="text-[9px] text-zinc-450 font-bold uppercase tracking-wider block dark:text-zinc-500">Recruiter Evaluation Narrative</span>
                  <div className="bg-zinc-900/40 p-5 rounded-xl border border-white/5 text-xs text-zinc-350 leading-relaxed whitespace-pre-wrap dark:bg-zinc-950/20 dark:border-white/5 dark:text-zinc-400">
                    {selectedReport.report_text}
                  </div>
                </div>

                {/* Lists section */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-6 pt-5 border-t border-white/5 dark:border-white/5">
                  
                  {/* Recurring issues */}
                  {selectedReport.recurring_issues && selectedReport.recurring_issues.length > 0 && (
                    <div className="space-y-3.5">
                      <span className="text-[9px] text-zinc-450 font-bold uppercase tracking-wider block flex items-center gap-1.5 dark:text-zinc-500">
                        <AlertCircle className="w-3.5 h-3.5 text-crimson" /> Persistent Gaps
                      </span>
                      <ul className="text-xs text-zinc-350 space-y-2 dark:text-zinc-400">
                        {selectedReport.recurring_issues.map((issue: string, i: number) => (
                          <li key={i} className="flex items-start gap-2">
                            <span className="h-1.5 w-1.5 rounded-full bg-crimson shrink-0 mt-1.5" />
                            <span>{issue}</span>
                          </li>
                        ))}
                      </ul>
                    </div>
                  )}

                  {/* Recommended focus */}
                  {selectedReport.recommended_focus && selectedReport.recommended_focus.length > 0 && (
                    <div className="space-y-3.5">
                      <span className="text-[9px] text-zinc-450 font-bold uppercase tracking-wider block flex items-center gap-1.5 dark:text-zinc-500">
                        <CheckCircle className="w-3.5 h-3.5 text-crimson" /> Action Target Focus
                      </span>
                      <ul className="text-xs text-zinc-350 space-y-2 dark:text-zinc-400">
                        {selectedReport.recommended_focus.map((focus: string, i: number) => (
                          <li key={i} className="flex items-start gap-2">
                            <span className="h-1.5 w-1.5 rounded-full bg-crimson shrink-0 mt-1.5" />
                            <span>{focus}</span>
                          </li>
                        ))}
                      </ul>
                    </div>
                  )}

                </div>

              </motion.div>
            ) : (
              <div className="bg-white/70 border border-white/5 text-center py-24 rounded-2xl flex flex-col items-center justify-center p-6 shadow-md dark:bg-zinc-900/35 dark:border-white/5">
                <FileText className="w-12 h-12 text-zinc-650 mb-4" />
                <h4 className="font-bold text-zinc-450 uppercase tracking-wider text-[10px] mb-1 dark:text-zinc-400">No review selected</h4>
                <p className="text-xs text-zinc-500 max-w-xs mt-1.5 leading-relaxed dark:text-zinc-500">
                  Compile a new review period report to view evaluation metrics and recruiter critiques.
                </p>
              </div>
            )}
          </AnimatePresence>
        </div>

      </div>

    </motion.div>
  );
};

